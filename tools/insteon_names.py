#!/usr/bin/env python3
"""Build the T-Embed's ``device_names:`` map from insteon-mqtt's device files.

insteon-mqtt configs list devices as ``- aa.bb.cc: "Name"`` entries in
``lights.yaml``, ``switches.yaml`` and so on (or inline under ``insteon:
devices:``). This collects every such entry and writes YAML for
``insteon_rf: device_names: !include <file>``. The names only label the
board's display; nothing is published with them.

Needs PyYAML (not an insteonrf dependency). Usage::

    python tools/insteon_names.py /k8s/insteon-config/*.yaml --plm 2B.93.07 \\
        > /k8s/homeassistant/esphome/common/insteon-names.yaml
"""

from __future__ import annotations

import argparse
import re
import sys
from typing import Any

import yaml

ADDRESS = re.compile(r"[0-9A-Fa-f]{2}[.:]?[0-9A-Fa-f]{2}[.:]?[0-9A-Fa-f]{2}")


class _Loader(yaml.SafeLoader):
    """SafeLoader that tolerates insteon-mqtt's !include / !rel_path tags."""


def _ignore(loader: yaml.SafeLoader, node: yaml.Node) -> None:
    return None


_Loader.add_constructor("!include", _ignore)
_Loader.add_constructor("!rel_path", _ignore)


def normalise(addr: str) -> str:
    hexd = re.sub(r"[^0-9A-Fa-f]", "", addr).upper()
    return f"{hexd[0:2]}.{hexd[2:4]}.{hexd[4:6]}"


#: Common words, shortened (left to right) only when a name is too long.
ABBREVIATIONS = {
    "Basement": "Bsmt", "Bathroom": "Bath", "Bedroom": "Bed", "Bottom": "Bot",
    "Dining": "Din", "Downstairs": "Dn", "Garage": "Gar", "Hallway": "Hall",
    "Kitchen": "Kit", "Lights": "Lts", "Light": "Lt", "Living": "Liv",
    "Lower": "Lo", "Master": "Mstr", "Overhead": "Ovhd", "Room": "Rm",
    "Sensor": "Sens", "Switch": "Sw", "Upper": "Up", "Upstairs": "Up",
}


def shorten(name: str, max_len: int) -> str:
    """Fit a name in ``max_len`` characters without losing what tells two
    devices apart, which is usually the end ("Dining Room Light - Back NL"
    vs "- Front NL"). Separators go first, then common words are abbreviated
    left to right; failing that, the middle is cut and the last word kept.
    """
    words = re.sub(r"\s*-\s*", " ", name).split()
    out = " ".join(words)
    for i, w in enumerate(words[:-1]):
        if len(out) <= max_len:
            break
        if w in ABBREVIATIONS:
            words[i] = ABBREVIATIONS[w]
            out = " ".join(words)
    if len(out) <= max_len:
        return out
    last = words[-1][:max_len]
    head = " ".join(words[:-1])[: max(0, max_len - len(last) - 1)].rstrip()
    return f"{head} {last}".strip()


def collect(node: Any, out: dict[str, str]) -> None:
    """Every ``address: "name"`` pair anywhere in a parsed YAML tree."""
    if isinstance(node, dict):
        for key, value in node.items():
            if isinstance(key, str) and ADDRESS.fullmatch(key.strip()) and isinstance(value, str):
                out.setdefault(normalise(key), value.strip())
            else:
                collect(value, out)
    elif isinstance(node, list):
        for item in node:
            collect(item, out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("files", nargs="+", help="insteon-mqtt YAML files")
    p.add_argument("--plm", help="the PLM's address, labelled 'PLM'")
    p.add_argument("--max-len", type=int, default=20, help="truncate names (the screen is narrow)")
    a = p.parse_args(argv)

    names: dict[str, str] = {}
    for path in a.files:
        with open(path) as f:
            collect(yaml.load(f, Loader=_Loader), names)
    if a.plm:
        names[normalise(a.plm)] = "PLM"

    print("# Generated by insteonrf tools/insteon_names.py from insteon-mqtt's device")
    print("# files; regenerate when devices change. Display labels only.")
    for addr in sorted(names):
        name = shorten(names[addr], a.max_len)
        print(f'"{addr}": {yaml.safe_dump(name, default_style=chr(34)).strip()}')
    print(f"# {len(names)} devices", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
